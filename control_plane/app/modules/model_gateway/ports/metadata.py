from collections.abc import Callable
from datetime import datetime
from typing import Any, Protocol

from control_plane.app.modules.model_gateway.domain import Deployment
from control_plane.app.modules.model_gateway.domain.metadata import (
    MetadataObservation,
    MetadataOutcome,
    MetadataSourceDefinition,
)
from control_plane.app.shared.idempotency import IdempotencyRepository


class MetadataSourceDirectoryPort(Protocol):
    def resolve(self, reference: str | None) -> tuple[str, MetadataSourceDefinition]: ...


class ModelMetadataPort(Protocol):
    def prepare(self, source: MetadataSourceDefinition) -> Any: ...
    # The guard returns current lease seconds remaining, or zero after losing the fence.
    def observe(
        self, prepared: Any, model_id: str, *, dispatch_guard: Callable[[], float]
    ) -> MetadataOutcome: ...
    def material_version(self, source: MetadataSourceDefinition) -> str: ...


class MetadataRepository(IdempotencyRepository, Protocol):
    db: Any

    def get(self, deployment_id: str, *, for_update: bool = False) -> Deployment | None: ...
    def observation(
        self, observation_id: str, *, for_update: bool = False
    ) -> MetadataObservation | None: ...
    def insert_observation(self, value: MetadataObservation) -> bool: ...
    def active_observation(self, deployment_id: str) -> bool: ...
    def save_observation(self, value: MetadataObservation, *, expected_revision: int) -> bool: ...
    def connection_busy(self, reference: str) -> bool: ...
    def queued_ids(self, *, limit: int) -> list[str]: ...
    def expired_ids(self, *, now: datetime, limit: int) -> list[str]: ...
    def list_observations(
        self, deployment_id: str, *, before_at: datetime | None, before_id: str | None, limit: int
    ) -> list[MetadataObservation]: ...
